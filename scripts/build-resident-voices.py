"""Render the villager voice banks with Kokoro v1.0.

Run from the repository root with kokoro-onnx and soundfile installed:
python scripts/build-resident-voices.py MODEL.onnx VOICES.bin

Model and voice pack: https://github.com/thewh1teagle/kokoro-onnx/releases/tag/model-files-v1.0
Model attribution: https://huggingface.co/hexgrad/Kokoro-82M
"""

import json
from pathlib import Path
import subprocess
import sys
import tempfile

from kokoro_onnx import Kokoro
import numpy as np
import soundfile as sf


CAST = {
    "ayse": ("bf_emma", 0.96),
    "hasan": ("bm_george", 0.90),
    "emre": ("bm_daniel", 1.04),
    "zeynep": ("bf_isabella", 1.09),
}

# English dialogue keeps the Turkish words from the original script. Supply their
# pronunciation in the model vocabulary using placeholders during phonemization.
PRONUNCIATION = {
    "Günaydın": ("gecko", "ɡynajdˈɯn"),
    "İyi akşamlar": ("llama", "iji akʃamlˈaɾ"),
    "Selam": ("penguin", "selˈam"),
    "çoban": ("parrot", "tʃobˈan"),
    "ağıl": ("lemur", "aːˈɯl"),
    "dere": ("otter", "deɾˈe"),
    "çay": ("emu", "tʃˈaj"),
    "Sağ ol": ("rabbit", "sˈaː ol"),
}


def render(model, line, voice, speed):
    phonemize = model.tokenizer.phonemize
    text = line.replace("’", "'")
    for word, (placeholder, _) in PRONUNCIATION.items():
        text = text.replace(word, placeholder)
    phonemes = phonemize(text, lang="en-gb")
    for word, (placeholder, ipa) in PRONUNCIATION.items():
        if word in line:
            phonemes = phonemes.replace(phonemize(placeholder, lang="en-gb"), ipa)
    samples, rate = model.create(phonemes, voice, speed=speed, is_phonemes=True)
    voiced = np.flatnonzero(np.abs(samples) > 0.008)
    if not len(voiced):
        raise ValueError(f"Empty recording for {line!r}")
    samples = samples[max(0, voiced[0] - rate // 30):voiced[-1] + rate // 16].copy()
    rms = np.sqrt(np.mean(samples ** 2))
    samples *= min(0.87 / np.max(np.abs(samples)), 0.12 / rms)
    edge = rate // 180
    samples[:edge] *= np.linspace(0, 1, edge)
    samples[-edge:] *= np.linspace(1, 0, edge)
    # Leave room for compressed-audio priming and avoid spilling into the next line.
    return np.pad(samples, (rate // 15, rate // 12)), rate


def main(model_path, voices_path):
    lines = json.loads(subprocess.check_output(["node", "scripts/resident-voice-lines.mjs"]))
    model = Kokoro(model_path, voices_path)
    output = Path("public/audio/villagers")
    output.mkdir(parents=True, exist_ok=True)
    banks = {}
    with tempfile.TemporaryDirectory() as scratch:
        for resident, (voice, speed) in CAST.items():
            reel = []
            cues = {}
            offset = 0
            for line in lines[resident]:
                samples, rate = render(model, line, voice, speed)
                cues[line] = [round(offset / rate, 4), round(len(samples) / rate, 4)]
                reel.append(samples)
                offset += len(samples)
            wave = Path(scratch) / f"{resident}.wav"
            sf.write(wave, np.concatenate(reel), rate, subtype="PCM_16")
            subprocess.run(["afconvert", "-f", "m4af", "-d", "aac", "-b", "48000",
                            str(wave), str(output / f"{resident}.m4a")], check=True)
            banks[resident] = cues
            print(f"{resident}: {len(cues)} lines, {offset / rate:.1f} seconds", flush=True)
    manifest = Path("src/audio/residentVoiceCues.ts")
    residents = [f"  {id}: {{\n" + "".join(
        f"    {json.dumps(line, ensure_ascii=False)}: {point},\n" for line, point in cues.items()) + "  },\n"
        for id, cues in banks.items()]
    manifest.write_text("// Generated by scripts/build-resident-voices.py. Times are seconds.\n"
                        "import type { ResidentId } from '../world/mapTypes';\n\n"
                        "export const voiceCues: Record<ResidentId, Readonly<Record<string, readonly [number, number]>>> = {\n"
                        + "".join(residents) + "};\n", encoding="utf-8")


if __name__ == "__main__":
    main(*sys.argv[1:])
